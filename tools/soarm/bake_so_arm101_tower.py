def check(text):
    """MuJoCo composes the written camera to the derived pose."""
    import mujoco

    m = mujoco.MjModel.from_xml_path(os.path.join(ROOT, OUT))
    ref = mujoco.MjModel.from_xml_path(os.path.join(ROOT, STOCK))
    assert m.nsite == ref.nsite + 1, (m.nsite, ref.nsite)
    assert mujoco.mj_name2id(m, mujoco.mjtObj.mjOBJ_SITE, "grasp_center") >= 0
    assert m.ncam == 1 and m.nbody == ref.nbody and m.nq == ref.nq, (
        "tower model counts drifted from stock: ncam %d nbody %d nq %d"
        % (m.ncam, m.nbody, m.nq)
    )
    # the floor gone (-1 geom) and the camera arm box added (+1); one mesh
    # more (the mount beside the stock part); one light fewer, no texture,
    # the groundplane material gone and the mount's added
    # +5 geoms: the two jaw collision MESHES became 4 + 3 boxes (the camera-arm
    # box was already counted against the stock's follower collision mesh).
    # step 8: the marker's boxes (the black square + the white runs) and its
    # two materials.
    n_marker = len(marker_geoms())
    assert m.ngeom == ref.ngeom + 5 + n_marker and m.nmesh == ref.nmesh + 1, (m.ngeom, m.nmesh)
    assert m.nlight == ref.nlight - 1 and m.ntex == 0 and m.nmat == ref.nmat + 2
    mk = [i for i in range(m.ngeom) if (mujoco.mj_id2name(m, mujoco.mjtObj.mjOBJ_GEOM, i) or "").startswith("aruco_")]
    assert len(mk) == n_marker, mk
    for i in mk:
        assert m.geom_group[i] == ARUCO_GROUP and m.geom_contype[i] == 0 and m.geom_conaffinity[i] == 0
    try:
        import cv2

        want = cv2.aruco.generateImageMarker(
            cv2.aruco.getPredefinedDictionary(cv2.aruco.DICT_4X4_50), ARUCO_ID, 6
        )
        got = np.array([[255 * int(ch) for ch in row] for row in ARUCO_BITS])
        assert np.array_equal(want, got), "ARUCO_BITS is not id %d:\n%s" % (ARUCO_ID, want // 255)
    except ImportError:
        pass
    # step 4a: the gripper body sits GRIPPER_STACK_EXTRA_M further out
    gb = mujoco.mj_name2id(m, mujoco.mjtObj.mjOBJ_BODY, "gripper")
    rb = mujoco.mj_name2id(ref, mujoco.mjtObj.mjOBJ_BODY, "gripper")
    assert abs((m.body_pos[gb][1] - ref.body_pos[rb][1]) + GRIPPER_STACK_EXTRA_M) < 1e-9, m.body_pos[gb]
    # step 7: the lift JOINT reaches the real rest stop, its ACTUATOR does not
    j = mujoco.mj_name2id(m, mujoco.mjtObj.mjOBJ_JOINT, "shoulder_lift")
    a = mujoco.mj_name2id(m, mujoco.mjtObj.mjOBJ_ACTUATOR, "shoulder_lift")
    assert abs(m.jnt_range[j][0] - LIFT_REST_STOP) < 1e-12, m.jnt_range[j]
    assert np.array_equal(m.actuator_ctrlrange[a], ref.actuator_ctrlrange[a])
    d = mujoco.MjData(m)
    mujoco.mj_forward(m, d)
    b = m.cam_bodyid[0]
    assert mujoco.mj_id2name(m, mujoco.mjtObj.mjOBJ_BODY, b) == "gripper"
    Rb = d.xmat[b].reshape(3, 3)
    pos_body = Rb.T @ (d.cam_xpos[0] - d.xpos[b])
    mat_body = Rb.T @ d.cam_xmat[0].reshape(3, 3)
    pos, xy = camera_in_gripper_body()
    dp = np.linalg.norm(pos_body - pos)
    dx = np.linalg.norm(mat_body[:, 0] - xy[:3])
    dy = np.linalg.norm(mat_body[:, 1] - xy[3:])
    assert dp < 1e-6 and dx < 1e-4 and dy < 1e-4, (
        "MuJoCo's composed wrist camera disagrees with the derivation:"
        " |dpos| %.2e |dx| %.2e |dy| %.2e" % (dp, dx, dy)
    )
    axis = -mat_body[:, 2]
    # the axis must point along the jaws (body -z) and back toward them (+y)
    assert axis[2] < -0.9 and axis[1] > 0.4, "optical axis %s" % axis.round(4)
    return m


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    os.chdir(ROOT)
    text = bake()
    if args.check:
        on_disk = open(OUT).read() if os.path.exists(OUT) else None
        if on_disk != text:
            print("STALE: %s differs from what the bake produces" % OUT)
            return 1
        m = check(text)
        pos, xy = camera_in_gripper_body()
        print("ok: %s is current; MuJoCo composes wrist_cam at %s in `gripper`"
              " (ncam %d, nbody %d)" % (OUT, _fmt(pos, 4), m.ncam, m.nbody))
        return 0
    open(OUT, "w").write(text)
    pos, xy = camera_in_gripper_body()
    print("wrote %s" % OUT)
    print("  wrist_cam pos (gripper body, m):", _fmt(pos, 5))
    print("  wrist_cam xyaxes:", _fmt(xy, 4), "| fovy %.4f" % FOVY_DEG)
    try:
        check(text)
        print("  MuJoCo agrees with the derivation")
    except ImportError:
        print("  (mujoco not importable here; run --check where it is)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
