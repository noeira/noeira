"""Bake Berkeley Humanoid Lite (BHL) as its authors simulate and train it.

    pixi run python tests/robots/bhl_bake.py            # write the assets
    pixi run python tests/robots/bhl_bake.py --check    # CI: fail on any diff

SOURCE: HybridRobotics/Berkeley-Humanoid-Lite-Assets at commit fc90fedd008b
(CC BY-SA 4.0), expected under `references/berkeley-humanoid-lite-assets-fc90fed/`:

    data/robots/berkeley_humanoid/berkeley_humanoid_lite/mjcf/berkeley_humanoid_lite.xml
        the MJCF BHL's own sim-to-sim check runs in MuJoCo
    berkeley_humanoid_lite_assets/robots/berkeley_humanoid_lite.py
        `HUMANOID_LITE_CFG`, the Isaac Lab articulation its policies train on

WHAT IT EMITS:

    noeira/envs/robots/assets/berkeley_humanoid_lite.xml
        BHL's MJCF with:
          * the visual meshes, their materials and the `<sensor>` block dropped
            (22 hinges, 14 box / cylinder collision geoms, nothing else reads
            them), so no mesh file ships;
          * a ground plane and a light;
          * `<option timestep="0.002">` instead of BHL's 0.0005 (see below);
          * SELF-COLLISIONS OFF (contype 1 / conaffinity 0 on the robot, the
            ground the other way round): `enabled_self_collisions=False` in
            `HUMANOID_LITE_CFG`. BHL's MJCF leaves them on;
          * 22 torque `<motor>`s, gear 1, ctrlrange = ± the training effort
            limit (6 N·m legs, 4 N·m arms) instead of forcerange ± 20;
          * the `stand` keyframe: `HUMANOID_LITE_CFG.init_state` (knees bent),
            the base lowered so that the soles rest on the ground.
        KEPT FROM THE MJCF, not from the Isaac config: armature 0.005 and
        frictionloss 0.1 on every hinge (Isaac: 0.007 hips and knees, 0.002
        ankles and arms, no friction). The real value is an open question of
        the hardware plan; the MJCF's is the one BHL checks its policies with.
    noeira/envs/robots/berkeley_humanoid_lite_pd.mojo
        per DoF, in the model's joint order: kp, kd, effort limit, speed limit,
        default angle (all `HUMANOID_LITE_CFG`), and the action scale 0.25 rad
        (BHL's `JointPositionActionCfg(scale=0.25)`).

⚠ THE TIMESTEP. BHL simulates at 0.5 ms; SuperMimic steps a 50 Hz control with
a handful of substeps. The env computes the PD torque itself every substep
under Euler (as `unitree_g1_mjlab` does), and with kd = 2 on a 0.005 kg·m²
armature the explicit damping term needs dt well under 2·0.005/2 = 5 ms. The
file takes 2 ms × 10 substeps; `tests/robots/bhl_ref.py` measures what that
costs against BHL's 0.5 ms in MuJoCo.

⚠ `references/` IS GITIGNORED. This is a local tool; the generated files are
what ships. The generated XML is a derivative of BHL's and stays CC BY-SA 4.0
(the header says so).
"""

import os
import re
import sys
import xml.etree.ElementTree as ET

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
REF = os.path.join(REPO, "references", "berkeley-humanoid-lite-assets-fc90fed")
REF_XML = os.path.join(REF, "data", "robots", "berkeley_humanoid", "berkeley_humanoid_lite", "mjcf",
                       "berkeley_humanoid_lite.xml")
REF_CFG = os.path.join(REF, "berkeley_humanoid_lite_assets", "robots", "berkeley_humanoid_lite.py")
ASSET_XML = os.path.join(REPO, "noeira", "envs", "robots", "assets", "berkeley_humanoid_lite.xml")
PD_MOJO = os.path.join(REPO, "noeira", "envs", "robots", "berkeley_humanoid_lite_pd.mojo")

TIMESTEP = 0.002
DECIMATION = 10          # 50 Hz control
ACTION_SCALE = 0.25      # BHL's JointPositionActionCfg(scale=0.25)

HEADER = """<!--
  Berkeley Humanoid Lite, GENERATED by tests/robots/bhl_bake.py. DO NOT EDIT.

  Derived from HybridRobotics/Berkeley-Humanoid-Lite-Assets (commit fc90fedd008b),
  (c) The Berkeley Humanoid Lite Project Developers, licensed CC BY-SA 4.0:
  https://creativecommons.org/licenses/by-sa/4.0/ . This file is a modified copy
  and is distributed under the same licence. The changes are listed in the bake script.
-->
"""


def read_cfg():
    """`HUMANOID_LITE_CFG` read as text (Isaac Lab is not importable here):
    the default joint angles and one (regex list, effort, speed, kp, kd) per actuator group."""
    src = open(REF_CFG).read()
    cfg = src[src.index("HUMANOID_LITE_CFG = ArticulationCfg("):]
    cfg = cfg[: cfg.index('"""Configuration')]
    init = cfg[cfg.index("joint_pos={"): cfg.index("joint_vel=")]
    default = {m.group(1): float(m.group(2)) for m in re.finditer(r'"([a-z_]+_joint)":\s*(-?[0-9.]+)', init)}
    groups = []
    for m in re.finditer(r'"(\w+)":\s*ImplicitActuatorCfg\((.*?)\n        \),', cfg, re.S):
        body = m.group(2)
        exprs = re.findall(r'"([^"]+)"', body[body.index("joint_names_expr"): body.index("]")])
        num = lambda key: float(re.search(key + r"=([0-9.]+)", body).group(1))  # noqa: E731
        groups.append(dict(name=m.group(1), exprs=exprs, effort=num("effort_limit"), speed=num("velocity_limit"),
                           kp=num("stiffness"), kd=num("damping")))
    soft = float(re.search(r"soft_joint_pos_limit_factor=([0-9.]+)", cfg).group(1))
    assert len(groups) == 3 and soft == 0.9, (groups, soft)
    return default, groups, soft


def actuator(groups, joint):
    hits = [g for g in groups if any(re.fullmatch(e, joint) for e in g["exprs"])]
    assert len(hits) == 1, (joint, [g["name"] for g in hits])
    return hits[0]


def bake_xml(default, groups):
    import mujoco

    root = ET.parse(REF_XML).getroot()
    for tag in ("asset", "sensor", "equality"):
        for el in root.findall(tag):
            root.remove(el)
    dropped = 0
    for parent in root.iter():
        for g in [g for g in parent.findall("geom") if g.get("class") == "visual"]:
            parent.remove(g)
            dropped += 1
    assert dropped == 26, dropped
    for d in root.iter("default"):
        for v in [c for c in d.findall("default") if c.get("class") == "visual"]:
            d.remove(v)
    coll = [d for d in root.iter("default") if d.get("class") == "collision"][0]
    coll.find("geom").set("contype", "1")
    coll.find("geom").set("conaffinity", "0")
    cls = [d for d in root.iter("default") if d.get("class") == "berkeley-humanoid-lite"][0]
    for p in cls.findall("position"):
        cls.remove(p)
    root.find("compiler").attrib.pop("meshdir", None)
    opt = root.find("option")
    if opt is None:
        opt = ET.SubElement(root, "option")
    opt.set("timestep", repr(TIMESTEP))
    opt.set("integrator", "Euler")
    opt.set("cone", "pyramidal")

    world = root.find("worldbody")
    light = ET.Element("light", pos="0 0 3.5", dir="0 0 -1", directional="true")
    floor = ET.Element("geom", name="floor", type="plane", size="0 0 0.05", pos="0 0 0", contype="0", conaffinity="1")
    world.insert(0, floor)
    world.insert(0, light)

    joints = [j.get("name") for j in root.iter("joint") if j.get("type") == "hinge"]
    assert len(joints) == 22, joints
    act = root.find("actuator")
    assert [m.get("joint") for m in act.findall("motor")] == joints, "actuator order is not the joint order"
    for m in act.findall("motor"):
        e = actuator(groups, m.get("joint"))["effort"]
        m.attrib.pop("forcerange")
        m.attrib.pop("class")
        m.set("gear", "1")
        m.set("ctrllimited", "true")
        m.set("ctrlrange", "%g %g" % (-e, e))

    # The stand keyframe: the default angles, the base lowered until the lowest sole corner is on the ground.
    ET.indent(root, space="  ")
    probe = mujoco.MjModel.from_xml_string(ET.tostring(root, encoding="unicode"))
    data = mujoco.MjData(probe)
    data.qpos[:] = probe.qpos0
    for k, name in enumerate(joints):
        data.qpos[7 + k] = default.get(name, 0.0)
    mujoco.mj_forward(probe, data)
    lowest = 1e9
    for g in range(probe.ngeom):
        if probe.geom_type[g] == mujoco.mjtGeom.mjGEOM_BOX and "ankle_roll" in probe.body(probe.geom_bodyid[g]).name:
            R = data.geom_xmat[g].reshape(3, 3)
            s = probe.geom_size[g]
            for sx in (-1, 1):
                for sy in (-1, 1):
                    for sz in (-1, 1):
                        lowest = min(lowest, (data.geom_xpos[g] + R @ (s * (sx, sy, sz)))[2])
    assert 0.0 < lowest < 0.1, lowest
    root_z = round(float(-lowest), 6)
    key = ET.SubElement(ET.SubElement(root, "keyframe"), "key", name="stand")
    key.set("qpos", " ".join(["0 0 %r 1 0 0 0" % root_z] + ["%g" % default.get(n, 0.0) for n in joints]))
    ET.indent(root, space="  ")
    text = HEADER + ET.tostring(root, encoding="unicode") + "\n"
    check = mujoco.MjModel.from_xml_string(text)
    assert (check.nq, check.nv, check.nu, check.njnt, check.nkey) == (29, 28, 22, 23, 1), "unexpected model size"
    return text, joints, root_z


def bake_pd(joints, default, groups, soft, root_z):
    L = ['"""Berkeley Humanoid Lite — PD tables, GENERATED, DO NOT EDIT.', "",
         "Regenerate with:  pixi run python tests/robots/bhl_bake.py",
         "CI checks it with: pixi run python tests/robots/bhl_bake.py --check", "",
         "Source of truth is HybridRobotics/Berkeley-Humanoid-Lite-Assets fc90fedd008b,",
         "`HUMANOID_LITE_CFG`: stiffness, damping, effort and velocity limits per actuator",
         "group, `init_state` as the default angles, and BHL's action scale of 0.25 rad.",
         "The torque law (computed in the env, every substep):", "",
         "    target = q_default + BHL_ACTION_SCALE · a          (no clip)",
         "    tau    = kp (target − q) − kd q̇, clipped to ± effort, and set to 0 when",
         "             it would push a joint already faster than its speed limit", '"""', "",
         "comptime BHL_N_DOF: Int = %d" % len(joints),
         "comptime BHL_SIM_TIMESTEP: Float64 = %r" % TIMESTEP,
         "comptime BHL_CONTROL_DECIMATION: Int = %d" % DECIMATION,
         "comptime BHL_INIT_ROOT_Z: Float64 = %r" % root_z,
         "comptime BHL_ACTION_SCALE: Float64 = %r" % ACTION_SCALE,
         "comptime BHL_SOFT_LIMIT_FACTOR: Float64 = %r" % soft, "", ""]

    def table(fn, doc, values, kind="Float64"):
        L.append("@always_inline")
        L.append("def %s(i: Int) -> %s:" % (fn, kind))
        L.append('    """%s"""' % doc)
        for k, v in enumerate(values):
            L.append("    %s i == %d:" % ("if" if k == 0 else "elif", k))
            L.append("        return %s" % (('"%s"' % v) if kind == "StaticString" else repr(float(v))))
        L.append("    return %s" % ('""' if kind == "StaticString" else "0.0"))
        L.extend(["", ""])

    acts = [actuator(groups, j) for j in joints]
    table("bhl_dof_name", "The hinge's name in the MJCF.", joints, "StaticString")
    table("bhl_kp", "Position gain, N·m/rad.", [a["kp"] for a in acts])
    table("bhl_kd", "Velocity gain, N·m·s/rad.", [a["kd"] for a in acts])
    table("bhl_effort", "Torque limit BHL trains under, N·m.", [a["effort"] for a in acts])
    table("bhl_speed", "Joint speed limit BHL trains under, rad/s.", [a["speed"] for a in acts])
    table("bhl_default_pos", "Default angle, rad (`init_state`).", [default.get(j, 0.0) for j in joints])
    while L[-1] == "":
        L.pop()
    return "\n".join(L) + "\n"


def main():
    check = "--check" in sys.argv
    for p in (REF_XML, REF_CFG):
        if not os.path.exists(p):
            sys.exit("missing reference file: " + p)
    default, groups, soft = read_cfg()
    xml, joints, root_z = bake_xml(default, groups)
    pd = bake_pd(joints, default, groups, soft, root_z)
    bad = 0
    for path, text in ((ASSET_XML, xml), (PD_MOJO, pd)):
        rel = os.path.relpath(path, REPO)
        if check:
            same = os.path.exists(path) and open(path).read() == text
            print(("ok       " if same else "DIFFERS  ") + rel)
            bad += not same
        else:
            open(path, "w").write(text)
            print("wrote " + rel)
    print("22 hinges, stand root z %r, groups %s" % (root_z, [(g["name"], g["kp"], g["kd"], g["effort"], g["speed"])
                                                                 for g in groups]))
    sys.exit(1 if bad else 0)


if __name__ == "__main__":
    main()
