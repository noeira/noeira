#!/usr/bin/env python3
"""Write `noeira/text/unicode_classes.mojo`: the code-point ranges of the regex
classes a pre-tokenizer needs — `\\p{L}` (letters), `\\p{N}` (numbers) and `\\s`
(white space) — from Python's `unicodedata`.

    python3 tools/text/gen_unicode_classes.py

`\\s` is Unicode's White_Space set, which is what Oniguruma (the regex engine of
Hugging Face `tokenizers`) means by `\\s` with Unicode: U+0009-000D, U+0020,
U+0085, and the Space/Line/Paragraph separators (Zs, Zl, Zp). The Unicode
version is the interpreter's (printed in the file); a code point whose class
changed between versions is the only way this can disagree with `tokenizers`,
and the tokenizer gate would show it.
"""

import os
import sys
import unicodedata

OUT = os.path.join(os.path.dirname(__file__), "..", "..", "noeira", "text", "unicode_classes.mojo")


def ranges(pred):
    out, start = [], None
    for cp in range(0x110000):
        if pred(cp):
            if start is None:
                start = cp
        elif start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def cat(cp):
    return unicodedata.category(chr(cp))


def emit(name, doc, rs):
    lo = ", ".join(f"0x{a:X}" for a, _ in rs)
    hi = ", ".join(f"0x{b:X}" for _, b in rs)
    return (f"comptime {name}_N: Int = {len(rs)}\n\"\"\"{doc}\"\"\"\n"
            f"comptime {name}_LO: Array[UInt32, {len(rs)}] = [{lo}]\n"
            f"comptime {name}_HI: Array[UInt32, {len(rs)}] = [{hi}]\n")


def main():
    letter = ranges(lambda c: cat(c).startswith("L"))
    number = ranges(lambda c: cat(c).startswith("N"))
    space = ranges(lambda c: (0x09 <= c <= 0x0D) or c == 0x20 or c == 0x85 or cat(c) in ("Zs", "Zl", "Zp"))
    body = f'''# +--------------------------------------------------------------------------+ #
# | Unicode classes for pre-tokenizers — GENERATED, do not edit
# +--------------------------------------------------------------------------+ #
"""`\\\\p{{L}}`, `\\\\p{{N}}` and `\\\\s` as sorted, disjoint code-point ranges.

Generated by `tools/text/gen_unicode_classes.py` from Python {sys.version.split()[0]}'s
`unicodedata` (Unicode {unicodedata.unidata_version}). `is_letter`, `is_number`,
`is_space` binary-search them; ASCII is answered without the tables.
"""

{emit("LETTER", "Ranges of General_Category L*.", letter)}
{emit("NUMBER", "Ranges of General_Category N*.", number)}
{emit("SPACE", "White space: U+0009-000D, U+0020, U+0085, Zs, Zl, Zp.", space)}

@always_inline
def _in[N: Int](cp: UInt32, lo: Array[UInt32, N], hi: Array[UInt32, N], n: Int) -> Bool:
    var a = 0
    var b = n - 1
    while a <= b:
        var m = (a + b) // 2
        if cp < lo[m]:
            b = m - 1
        elif cp > hi[m]:
            a = m + 1
        else:
            return True
    return False


def is_letter(cp: UInt32) -> Bool:
    if cp < 128:
        return (cp >= 65 and cp <= 90) or (cp >= 97 and cp <= 122)
    return _in(cp, materialize[LETTER_LO](), materialize[LETTER_HI](), LETTER_N)


def is_number(cp: UInt32) -> Bool:
    if cp < 128:
        return cp >= 48 and cp <= 57
    return _in(cp, materialize[NUMBER_LO](), materialize[NUMBER_HI](), NUMBER_N)


def is_space(cp: UInt32) -> Bool:
    if cp < 128:
        return (cp >= 9 and cp <= 13) or cp == 32
    return _in(cp, materialize[SPACE_LO](), materialize[SPACE_HI](), SPACE_N)
'''
    with open(OUT, "w") as f:
        f.write(body)
    print(f"{OUT}: {len(letter)} letter, {len(number)} number, {len(space)} space ranges "
          f"(Unicode {unicodedata.unidata_version})")


if __name__ == "__main__":
    main()
