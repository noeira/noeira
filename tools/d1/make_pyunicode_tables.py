#!/usr/bin/env python3
"""Python's own character classes and case/accent maps, as Mojo tables, for
`noeira/text/pyre.mojo` and d1's parser (`noeira/llm/d1/parsing.mojo`;
docs/NN_MODEL_PORTS_PLAN.md §12.9, T6).

    ~/Documents/noeira-parakeet/d1ref-venv/bin/python tools/d1/make_pyunicode_tables.py \
        > noeira/text/pyunicode_tables.mojo

Run it with the Python d1's reference runs on (the Orin's d1ref-venv): the
tables are that interpreter's `unicodedata` (its version is written in the
header).

- DECIMAL: `str.isdecimal()` (Unicode Nd), what `re`'s `\\d` matches and `int()`
  reads, each range starting at its zero.
- DIGIT: `str.isdigit()` (Nd and the other digits: superscripts, circled ones).
- WORD: `str.isalnum()` — `re`'s `\\w` with `_`.
- LOWER: `str.lower()` where it is ONE other character (over the same range).
- FOLD: d1's `_fold` per character — `casefold()`, NFKD, combining marks
  dropped — wherever it changes the character, over all of Unicode but the
  Hangul syllables, which `parsing.fold` decomposes by Unicode's arithmetic;
  `main` checks that nothing outside the table folds.
"""

import sys
import unicodedata

FOLD_BLOCKS = [(0x0000, 0xABFF), (0xD7A4, 0xD7FF), (0xE000, 0x10FFFF)]  # all but Hangul syllables and surrogates


def ranges(pred):
    out, start = [], None
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            ok = False
        else:
            ok = pred(chr(cp))
        if ok and start is None:
            start = cp
        elif not ok and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def fold(c):
    return "".join(x for x in unicodedata.normalize("NFKD", c.casefold()) if not unicodedata.combining(x))


def arr(name, ty, xs):
    body = ", ".join(hex(x) for x in xs)
    return f"comptime {name}: Array[{ty}, {len(xs)}] = [{body}]\n"


def main():
    dec = ranges(str.isdecimal)
    for lo, hi in dec:  # every Nd run starts at a zero: value = (cp - lo) % 10
        assert unicodedata.decimal(chr(lo)) == 0, hex(lo)
    dig = ranges(str.isdigit)
    word = ranges(lambda c: c.isalnum() or c == "_")
    lower = [(cp, ord(chr(cp).lower())) for lo, hi in FOLD_BLOCKS for cp in range(lo, hi + 1)
             if len(chr(cp).lower()) == 1 and chr(cp).lower() != chr(cp)]
    folds = [(cp, fold(chr(cp))) for lo, hi in FOLD_BLOCKS for cp in range(lo, hi + 1) if fold(chr(cp)) != chr(cp)]
    inside = {cp for lo, hi in FOLD_BLOCKS for cp in range(lo, hi + 1)}
    outside = sum(1 for cp in range(0x110000) if cp not in inside and not 0xAC00 <= cp <= 0xD7A3
                  and not 0xD800 <= cp <= 0xDFFF and fold(chr(cp)) != chr(cp))
    print(f"characters outside the blocks (and Hangul) that Python folds: {outside}", file=sys.stderr)
    out = []
    w = out.append
    w("# +--------------------------------------------------------------------------+ #\n")
    w("# | GENERATED by tools/d1/make_pyunicode_tables.py — do not edit\n")
    w("# +--------------------------------------------------------------------------+ #\n")
    w(f'"""Python {sys.version.split()[0]}\'s character classes, Unicode {unicodedata.unidata_version}: '
      "see the generator's header."
      '"""\n\n')
    w(f"comptime PY_UNICODE_VERSION = \"{unicodedata.unidata_version}\"\n\n")
    for name, rs in (("DECIMAL", dec), ("DIGIT", dig), ("WORD", word)):
        w(f"comptime {name}_N: Int = {len(rs)}\n")
        w(arr(f"{name}_LO", "UInt32", [a for a, _ in rs]))
        w(arr(f"{name}_HI", "UInt32", [b for _, b in rs]))
        w("\n")
    w(f"comptime LOWER_N: Int = {len(lower)}\n")
    w(arr("LOWER_FROM", "UInt32", [a for a, _ in lower]))
    w(arr("LOWER_TO", "UInt32", [b for _, b in lower]))
    w("\n")
    blob, offs = [], []
    for _, s in folds:
        offs.append(len(blob))
        blob.extend(ord(c) for c in s)
    offs.append(len(blob))
    w(f"comptime FOLD_N: Int = {len(folds)}\n")
    w(arr("FOLD_FROM", "UInt32", [a for a, _ in folds]))
    w(arr("FOLD_OFF", "UInt32", offs))
    w(f"comptime FOLD_OUT_N: Int = {len(blob)}\n")
    w(arr("FOLD_OUT", "UInt32", blob) if blob else "")
    sys.stdout.write("".join(out))
    print(f"DECIMAL {len(dec)} ranges, DIGIT {len(dig)}, WORD {len(word)}, LOWER {len(lower)}, FOLD {len(folds)} "
          f"({len(blob)} code points)", file=sys.stderr)


if __name__ == "__main__":
    main()
