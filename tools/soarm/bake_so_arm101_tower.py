def load_stl(path):
    """Triangles [n, 3, 3] of a binary or ASCII STL, in the file's units."""
    b = open(path, "rb").read()
    if b[:5] == b"solid" and b"facet" in b[:400]:
        vs = []
        for line in b.decode(errors="ignore").splitlines():
            t = line.strip().split()
            if t and t[0] == "vertex":
                vs.append([float(x) for x in t[1:4]])
        return np.array(vs).reshape(-1, 3, 3)
    n = struct.unpack("<I", b[80:84])[0]
    a = np.frombuffer(
        b[84 : 84 + n * 50],
        dtype=np.dtype([("n", "<3f4"), ("v", "<9f4"), ("a", "<u2")]),
    )
    return a["v"].reshape(-1, 3, 3).astype(np.float64)


def _slab(v, axis, lo, hi):
    m = (v[:, axis] >= lo) & (v[:, axis] <= hi)
    return v[m]


def _measure_wrist_mesh():
    """The two facts the camera pose rests on, read off the STLs."""
    stock = load_stl(os.path.join(ROOT, MESHDIR, STOCK_MESH + ".stl"))
    mount = load_stl(os.path.join(ROOT, MESHDIR, MOUNT_MESH + ".stl"))
    sv = stock.reshape(-1, 3) * 1000.0  # metres -> mm
    mv = mount.reshape(-1, 3)
    # 1. same frame: the servo pocket's x/y extents agree slice by slice.
    for lo, hi in ((20, 60), (60, 100), (100, 105.4)):
        a = _slab(sv, 2, lo, hi)
        b = _slab(mv, 2, lo, hi)
        for k in (0, 1):
            for f in (np.min, np.max):
                da = abs(f(a[:, k]) - f(b[:, k]))
                assert da < 0.5, (
                    "stock and mount meshes disagree by %.2f mm on axis %d in"
                    " z[%g, %g]: they are NOT in one frame" % (da, k, lo, hi)
                )
    # 2. the plate: a planar face with the doc's normal, at the doc's centre,
    #    and its opposite face `PLATE_THICKNESS_MM` behind it.
    n = np.cross(mount[:, 1] - mount[:, 0], mount[:, 2] - mount[:, 0])
    area = np.linalg.norm(n, axis=1) / 2
    nn = n / np.maximum(np.linalg.norm(n, axis=1, keepdims=True), 1e-12)
    c = mount.mean(1)
    front = (area > 1e-6) & (nn @ PLATE_NORMAL > 0.999) & (c[:, 1] > 45)
    back = (area > 1e-6) & (nn @ (-PLATE_NORMAL) > 0.999) & (c[:, 1] > 45)
    for m, name in ((front, "front"), (back, "back")):
        assert area[m].sum() > 1000, "no %s plate face found" % name
    cf = (c[front] * area[front, None]).sum(0) / area[front].sum()
    cb = (c[back] * area[back, None]).sum(0) / area[back].sum()
    assert np.linalg.norm(cf - PLATE_FACE_MM) < 0.5, (
        "plate face centre %s vs the doc's %s" % (cf.round(2), PLATE_FACE_MM)
    )
    thick = float((cf - cb) @ PLATE_NORMAL)
    assert abs(thick - PLATE_THICKNESS_MM) < 0.2, (
        "plate thickness %.2f mm, doc says %g" % (thick, PLATE_THICKNESS_MM)
    )
    return cf, thick


def _quat_to_mat(q):
    w, x, y, z = q
    return np.array(
        [
            [1 - 2 * (y * y + z * z), 2 * (x * y - z * w), 2 * (x * z + y * w)],
            [2 * (x * y + z * w), 1 - 2 * (x * x + z * z), 2 * (y * z - x * w)],
            [2 * (x * z - y * w), 2 * (y * z + x * w), 1 - 2 * (x * x + y * y)],
        ]
    )


def camera_in_gripper_body():
    """(pos [m], xyaxes [6]) of the wrist camera in the `gripper` body frame.

    Derived from the doc's mesh-frame numbers and the stock geom's transform —
    the SAME rule `camera-rig.md` §6 spells out — so `--check` can compare it
    against what MuJoCo composes from the written attributes.
    """
    n = PLATE_NORMAL / np.linalg.norm(PLATE_NORMAL)
    pupil_mm = PLATE_FACE_MM + PUPIL_ALONG_NORMAL_MM * n
    R = _quat_to_mat([float(v) for v in STOCK_GEOM_QUAT.split()])
    p0 = np.array([float(v) for v in STOCK_GEOM_POS.split()])
    pos = R @ (pupil_mm / 1000.0) + p0
    axis = R @ n  # optical axis in the body frame
    z_cam = -axis
    # image-up: jaws at the bottom of the frame (see the module docstring).
    y_cam = -np.cross(z_cam, np.array([1.0, 0.0, 0.0]))
    y_cam /= np.linalg.norm(y_cam)
    x_cam = np.cross(y_cam, z_cam)
    return pos, np.concatenate([x_cam, y_cam])


def _mat_to_quat(R):
    """(w, x, y, z) of a proper rotation matrix."""
    w = math.sqrt(max(0.0, 1.0 + R[0, 0] + R[1, 1] + R[2, 2])) / 2.0
    x = math.copysign(math.sqrt(max(0.0, 1.0 + R[0, 0] - R[1, 1] - R[2, 2])) / 2.0, R[2, 1] - R[1, 2])
    y = math.copysign(math.sqrt(max(0.0, 1.0 - R[0, 0] + R[1, 1] - R[2, 2])) / 2.0, R[0, 2] - R[2, 0])
    z = math.copysign(math.sqrt(max(0.0, 1.0 - R[0, 0] - R[1, 1] + R[2, 2])) / 2.0, R[1, 0] - R[0, 1])
    return np.array([w, x, y, z])


def marker_in_gripper_body():
    """(centre [m], R [3x3]) of the ArUco marker in the `gripper` body frame:
    its columns are the marker's +x, +y and its normal (+z, out of the print).

    ON THE BACK FACE OF THE CAMERA PLATE, CENTRED — the front face's centre
    (where the lens is: the mount's 27 x 27 hole pattern is centred on it to
    0.0 mm) pushed `PLATE_THICKNESS_MM` back. Fitted independently from the 30
    extrinsics captures (`camera_overhead.txt.poses.txt`: marker corners
    solvePnP'd, gripper FK from the raw ticks through the measured zero, camera
    and offset solved together, rms 9.9 mm): normal (0.046, -0.399, 0.916),
    2.3 deg from the plate's; in-plane +x (-0.02, 0.92, 0.40) — the print's
    +y along body -x, the fixed jaw's side (orientation scatter 4.3 deg
    median); centre 6 mm from this one in-plane (inside the fit's noise, which
    trades with the camera's own xy), 2.5 mm into the plate.
    """
    n = PLATE_NORMAL / np.linalg.norm(PLATE_NORMAL)
    back_mm = PLATE_FACE_MM - PLATE_THICKNESS_MM * n
    R = _quat_to_mat([float(v) for v in STOCK_GEOM_QUAT.split()])
    p0 = np.array([float(v) for v in STOCK_GEOM_POS.split()])
    centre = R @ (back_mm / 1000.0) + p0
    ez = R @ (-n)
    ey = np.array([-1.0, 0.0, 0.0])
    ex = np.cross(ey, ez)
    return centre, np.stack([ex, ey, ez], axis=1)


def marker_geoms():
    """The marker as boxes: the black square, then each row's white runs
    0.2 mm proud of it. Visual only (group `ARUCO_GROUP`, no contacts)."""
    c, R = marker_in_gripper_body()
    q = _fmt(_mat_to_quat(R), 7)
    cell = ARUCO_MM / 6000.0
    out = []

    def box(name, u, v, hu, hv, lift, hz, mat):
        p = c + R @ np.array([u, v, lift])
        out.append(
            '                <geom type="box" name="%s" group="%d" contype="0"'
            ' conaffinity="0" pos="%s" quat="%s" size="%s" material="%s"/>'
            % (name, ARUCO_GROUP, _fmt(p, 7), q, _fmt([hu, hv, hz], 6), mat)
        )

    box("aruco_black", 0.0, 0.0, 3 * cell, 3 * cell, 0.0002, 0.0002, "aruco_black")
    k = 0
    for r, row in enumerate(ARUCO_BITS):
        col = 0
        while col < 6:
            if row[col] != "1":
                col += 1
                continue
            end = col
            while end < 6 and row[end] == "1":
                end += 1
            u = ((col + end) / 2.0 - 3.0) * cell
            v = (3.0 - (r + 0.5)) * cell
            box("aruco_white_%d" % k, u, v, (end - col) * cell / 2, cell / 2, 0.0005, 0.0001, "aruco_white")
            k += 1
            col = end
    return out


def _fmt(v, nd=6):
    return " ".join(("%.*g" % (nd, float(x) + 0.0)) for x in v)


